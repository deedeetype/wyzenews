// Build step: copy ONLY the public files into dist/.
// Anything not listed here (netlify/functions, lib/, README, SQL, backups...) is never published.

import { cpSync, existsSync, mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const SITE = 'https://wyzenews.com';
const OUT = 'dist';

const PUBLIC_FILES = [
  'index.html',
  'archive.html',
  'privacy.html',
  'unsubscribe.html',
  'confirm.html',
  '404.html',
  'style.css',
  'app.js',
  'digest.js',
  'archive.js',
  'unsubscribe.js',
  'confirm.js',
  'robots.txt',
];
const PUBLIC_DIRS = ['assets', 'breaking'];

// Pinned third-party script: add Subresource Integrity so a tampered CDN copy is refused.
const PANZOOM_TAG = '<script src="https://unpkg.com/@panzoom/panzoom@4.5.1/dist/panzoom.min.js"></script>';
const PANZOOM_SRI =
  '<script src="https://unpkg.com/@panzoom/panzoom@4.5.1/dist/panzoom.min.js" ' +
  'integrity="sha384-ZOYffjPUyf23W5DufkQVkrN7uZvIMRRCPo64S2N2S0mFM9+bFZpn2/MQTy2O35gF" ' +
  'crossorigin="anonymous"></script>';

rmSync(OUT, { recursive: true, force: true });
mkdirSync(OUT, { recursive: true });

for (const file of PUBLIC_FILES) {
  if (!existsSync(file)) throw new Error(`Missing public file: ${file}`);
  cpSync(file, join(OUT, file));
}
for (const dir of PUBLIC_DIRS) {
  cpSync(dir, join(OUT, dir), { recursive: true });
}

// Add SRI to every generated story page.
let patched = 0;
function walk(dir) {
  for (const name of readdirSync(dir)) {
    const path = join(dir, name);
    if (statSync(path).isDirectory()) {
      walk(path);
    } else if (name.endsWith('.html')) {
      const html = readFileSync(path, 'utf8');
      if (html.includes(PANZOOM_TAG)) {
        writeFileSync(path, html.replaceAll(PANZOOM_TAG, PANZOOM_SRI));
        patched++;
      }
    }
  }
}
walk(join(OUT, 'breaking'));

// sitemap.xml, generated from the digest index.
const index = JSON.parse(readFileSync('breaking/index.json', 'utf8'));
const urls = [`${SITE}/`, `${SITE}/archive`, `${SITE}/privacy`];
for (const date of Object.keys(index).sort().reverse()) {
  for (const story of index[date].stories || []) {
    if (/^breaking\/[\w\-/.]+\.html$/.test(story.url)) urls.push(`${SITE}/${story.url}`);
  }
}
writeFileSync(
  join(OUT, 'sitemap.xml'),
  '<?xml version="1.0" encoding="UTF-8"?>\n' +
    '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n' +
    urls.map((u) => `  <url><loc>${u}</loc></url>`).join('\n') +
    '\n</urlset>\n'
);

// _headers: security headers for static responses.
// CSP rules are listed per path (never overlapping) so that only one policy applies to a page.
const COMMON = [
  'X-Content-Type-Options: nosniff',
  'X-Frame-Options: DENY',
  'Referrer-Policy: strict-origin-when-cross-origin',
  'Permissions-Policy: camera=(), microphone=(), geolocation=(), payment=(), interest-cohort=()',
  'Strict-Transport-Security: max-age=31536000; includeSubDomains',
  'Cross-Origin-Opener-Policy: same-origin',
];
const CSP_BASE =
  "default-src 'self'; img-src 'self' data:; style-src 'self' 'unsafe-inline'; " +
  "connect-src 'self' https://ingesteer.services-prod.nsvcs.net; " +
  "object-src 'none'; base-uri 'self'; form-action 'self'; frame-ancestors 'none'";
const CSP_STRICT = `${CSP_BASE}; script-src 'self'`;
// Story pages are generated by the publishing pipeline with inline scripts + the pinned panzoom CDN script.
const CSP_STORIES = `${CSP_BASE}; script-src 'self' 'unsafe-inline' https://unpkg.com`;

const strictPaths = ['/', '/404.html'];
for (const page of ['index', 'archive', 'privacy', 'unsubscribe', 'confirm']) {
  strictPaths.push(`/${page}`, `/${page}.html`);
}

let headers = `/*\n${COMMON.map((h) => `  ${h}`).join('\n')}\n\n`;
for (const path of strictPaths) {
  headers += `${path}\n  Content-Security-Policy: ${CSP_STRICT}\n\n`;
}
headers += `/breaking/*\n  Content-Security-Policy: ${CSP_STORIES}\n`;
writeFileSync(join(OUT, '_headers'), headers);

console.log(`Build OK: ${urls.length} sitemap URLs, ${patched} story pages patched with SRI.`);
